  final String id;
  final String name;
  final String code;
  final String departmentId;
  final String facultyId;
  final int credits;

  const Subject({
    required this.id,
    required this.name,
    required this.code,
    required this.departmentId,
    required this.facultyId,
    required this.credits,
  });
}
